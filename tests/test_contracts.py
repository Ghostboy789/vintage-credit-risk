# ---- CONTRACTS.md and the specs agree --------------------------------------------------------
def _section(title: str) -> str:
    m = re.search(rf"^### `{re.escape(title)}`.*?(?=^### |^## |\Z)", CONTRACTS_MD, re.M | re.S)
    assert m, f"CONTRACTS.md has no section ### `{title}`"
    return m.group(0)


@pytest.mark.parametrize("name", list(C.MARTS) + list(C.MODEL_OUTPUTS))
def test_contracts_md_lists_every_column(name):
    spec = C.MARTS.get(name) or C.MODEL_OUTPUTS[name]
    section = _section(name)
    documented = set(re.findall(r"^\| `([a-z0-9_]+)` \|", section, re.M))
    assert documented == set(spec["columns"]), (
        f"{name}: only in spec {set(spec['columns']) - documented}, "
        f"only in CONTRACTS.md {documented - set(spec['columns'])}"
    )


def _keys(spec) -> set[str]:
    out = set()
    if isinstance(spec, dict):
        for k, v in spec.items():
            out.add(k)
            out |= _keys(v)
    elif isinstance(spec, list):
        out |= _keys(spec[0])
    return out


@pytest.mark.parametrize("name", list(C.ARTEFACTS))
def test_contracts_md_documents_every_artefact_field(name):
    section = _section(f"artefacts/{name}.json")
    common = set(C.ENVELOPE) | set(C.PASS_RULES[0])  # documented once under "Common rules"
    missing = sorted(k for k in _keys(C.ARTEFACTS[name]) - common if f"`{k}`" not in section)
    assert not missing, f"{name}: fields not documented in CONTRACTS.md: {missing}"
