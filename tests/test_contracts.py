# ---- the checker catches what it should ------------------------------------------------------
def _rewrite(src: Path, dst: Path, fn) -> Path:
    table = fn(pq.read_table(src))
    pq.write_table(table, dst)
    return dst


def test_checker_flags_missing_column_wrong_type_and_extra(tmp_path):
    src = FIX / "marts" / "dim_date.parquet"
    p = _rewrite(src, tmp_path / "a.parquet", lambda t: t.drop(["market_rate_pct"]))
    assert any("missing column market_rate_pct" in e for e in C.check_mart("dim_date", p))
    p = _rewrite(
        src, tmp_path / "b.parquet", lambda t: t.set_column(1, "year", t["year"].cast(pa.string()))
    )
    assert any("column year is string" in e for e in C.check_mart("dim_date", p))
    p = _rewrite(
        src, tmp_path / "c.parquet", lambda t: t.append_column("extra", pa.array([1] * t.num_rows))
    )
    assert any("unexpected column extra" in e for e in C.check_mart("dim_date", p))


def test_checker_flags_duplicate_keys_nulls_and_bad_values(tmp_path):
    src = FIX / "marts" / "dim_date.parquet"
    p = _rewrite(src, tmp_path / "d.parquet", lambda t: pa.concat_tables([t, t.slice(0, 1)]))
    assert any("duplicate key" in e for e in C.check_mart("dim_date", p))

    def bad_period(t):
        vals = t["economic_period"].to_pylist()
        vals[0] = "boom"
        return t.set_column(
            t.schema.get_field_index("economic_period"), "economic_period", pa.array(vals)
        )

    p = _rewrite(src, tmp_path / "e.parquet", bad_period)
    assert any("outside the contract" in e for e in C.check_mart("dim_date", p))

    def null_year(t):
        vals = t["year"].to_pylist()
        vals[0] = None
        return t.set_column(1, "year", pa.array(vals, pa.int64()))

    p = _rewrite(src, tmp_path / "f.parquet", null_year)
    assert any("null(s) in non-null column year" in e for e in C.check_mart("dim_date", p))


def test_checker_flags_bad_artefacts():
    good = json.loads((FIX / "artefacts" / "capital.json").read_text(encoding="utf-8"))
    assert C.check_artefact("capital", good) == []

    missing = copy.deepcopy(good)
    del missing["limits"]
    assert any("missing key limits" in e for e in C.check_artefact("capital", missing))

    extra = copy.deepcopy(good)
    extra["headline"] = 1
    assert any("unexpected key headline" in e for e in C.check_artefact("capital", extra))

    outside = copy.deepcopy(good)
    outside["by_grade"][0]["pd"]["value"] = 5.0
    assert any("outside its interval" in e for e in C.check_artefact("capital", outside))

    no_reason = copy.deepcopy(good)
    no_reason["by_grade"][0]["k"]["ci_method"] = "bootstrap"
    assert any("must start with 'none:'" in e for e in C.check_artefact("capital", no_reason))

    bad_enum = copy.deepcopy(good)
    bad_enum["status"] = "done"
    assert any("not one of" in e for e in C.check_artefact("capital", bad_enum))

    wrong_name = copy.deepcopy(good)
    wrong_name["artefact"] = "ecl"
    assert any("must be 'capital'" in e for e in C.check_artefact("capital", wrong_name))


